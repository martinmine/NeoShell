/// <summary>
/// A caption's art: one colour per row in the middle, the frame's edge columns per row, a shade near each end (an
/// offset added to the row's colour per column), and the ends' first and last rows as measured (the rounded top
/// corners' highlight and the bottom's shading don't separate into row and column).
/// </summary>
internal sealed class CaptionArt
{
    private readonly uint[] _middle;
    private readonly uint[][] _edgeLeft, _edgeRight, _cornerLeft, _cornerRight, _bottomLeft, _bottomRight;
    private readonly int[][] _shadeLeft, _shadeRight;

    public CaptionArt(string mid, string[] edgeLeft, string[] edgeRight, string shadeLeft, string shadeRight,
        string[] cornerLeft, string[] cornerRight, string[] bottomLeft, string[] bottomRight)
    {
        _middle = Colors(mid);
        _edgeLeft = [.. edgeLeft.Select(Colors)];
        _edgeRight = [.. edgeRight.Select(Colors)];
        _cornerLeft = [.. cornerLeft.Select(Colors)];
        _cornerRight = [.. cornerRight.Select(Colors)];
        _bottomLeft = [.. bottomLeft.Select(Colors)];
        _bottomRight = [.. bottomRight.Select(Colors)];
        _shadeLeft = Offsets(shadeLeft);
        _shadeRight = Offsets(shadeRight);
    }

    /// <summary>How many rows XP drew.</summary>
    public int Rows => _middle.Length;

    /// <summary>The colour (RRGGBB) at column <paramref name="x"/> of art row <paramref name="row"/>, in a caption <paramref name="width"/> wide.</summary>
    public uint Pixel(int x, int row, int width)
    {
        int edgeLeft = _edgeLeft[0].Length, edgeRight = _edgeRight[0].Length;
        int fromRight = width - 1 - x;
        if (fromRight < edgeRight)
            return _edgeRight[row][edgeRight - 1 - fromRight];
        if (x < edgeLeft)
            return _edgeLeft[row][x];
        int cornerRight = _cornerRight[0].Length, cornerLeft = _cornerLeft[0].Length;
        if (row < _cornerRight.Length && fromRight < edgeRight + cornerRight)
            return _cornerRight[row][cornerRight - 1 - (fromRight - edgeRight)];
        if (row < _cornerLeft.Length && x < edgeLeft + cornerLeft)
            return _cornerLeft[row][x - edgeLeft];
        int fromBottom = _middle.Length - 1 - row;
        if (fromBottom < _bottomRight.Length && fromRight < edgeRight + cornerRight)
            return _bottomRight[_bottomRight.Length - 1 - fromBottom][cornerRight - 1 - (fromRight - edgeRight)];
        if (fromBottom < _bottomLeft.Length && x < edgeLeft + cornerLeft)
            return _bottomLeft[_bottomLeft.Length - 1 - fromBottom][x - edgeLeft];
        if (fromRight < edgeRight + _shadeRight.Length)
            return Add(_middle[row], _shadeRight[_shadeRight.Length - 1 - (fromRight - edgeRight)]);
        if (x < edgeLeft + _shadeLeft.Length)
            return Add(_middle[row], _shadeLeft[x - edgeLeft]);
        return _middle[row];
    }

    private static uint Add(uint color, int[] offset)
    {
        int Channel(int shift, int delta) => Math.Clamp((int)((color >> shift) & 255) + delta, 0, 255);
        return (uint)((Channel(16, offset[0]) << 16) | (Channel(8, offset[1]) << 8) | Channel(0, offset[2]));
    }

    internal static uint[] Colors(string colors) => [.. colors.Split(' ').Select(hex => Convert.ToUInt32(hex, 16))];

    private static int[][] Offsets(string offsets) =>
        [.. offsets.Split(' ').Select(offset => offset.Split(',').Select(int.Parse).ToArray())];
}

/// <summary>The borders below the caption: left from outside in, right from inside out, bottom from the top down, and the mitred bottom corners.</summary>
internal sealed class BorderArt(string left, string right, string bottom, string[] bottomLeft, string[] bottomRight)
{
    public readonly uint[] Left = CaptionArt.Colors(left), Right = CaptionArt.Colors(right), Bottom = CaptionArt.Colors(bottom);
    public readonly uint[][] BottomLeft = [.. bottomLeft.Select(CaptionArt.Colors)];
    public readonly uint[][] BottomRight = [.. bottomRight.Select(CaptionArt.Colors)];

    public int Width => Left.Length;
}

/// <summary>A caption button's face: control colours on a grid (<see cref="LunaArt.MeshNodes21"/>), interpolated bilinearly.</summary>
internal sealed class FaceArt(float borderOpacity, float glyphOpacity, string[] mesh)
{
    public readonly float BorderOpacity = borderOpacity, GlyphOpacity = glyphOpacity;
    private readonly uint[][] _mesh = [.. mesh.Select(CaptionArt.Colors)];

    public uint At(int[] nodes, int x, int y)
    {
        (int row, float ty) = Cell(nodes, y);
        (int column, float tx) = Cell(nodes, x);
        int Channel(int shift)
        {
            float top = ((_mesh[row][column] >> shift) & 255) * (1 - tx) + ((_mesh[row][column + 1] >> shift) & 255) * tx;
            float bottom = ((_mesh[row + 1][column] >> shift) & 255) * (1 - tx) + ((_mesh[row + 1][column + 1] >> shift) & 255) * tx;
            return (int)MathF.Round(top * (1 - ty) + bottom * ty);
        }
        return (uint)((Channel(16) << 16) | (Channel(8) << 8) | Channel(0));
    }

    private static (int Index, float Fraction) Cell(int[] nodes, int value)
    {
        int i = 0;
        while (i < nodes.Length - 2 && value >= nodes[i + 1])
            i++;
        return (i, Math.Clamp((value - nodes[i]) / (float)(nodes[i + 1] - nodes[i]), 0, 1));
    }
}
